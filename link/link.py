#!/usr/bin/env python3
"""Links the compiled game objects into a PSP module, stubbing whatever
nothing defines (the platform layer that doesn't exist yet), and reports
sizes. Run after ../build.py."""
import os, re, subprocess
HERE = os.path.dirname(os.path.abspath(__file__))
SDK = "/opt/psp/pspdev/psp/sdk"
objs = [l for l in open(os.path.join(HERE, "../build/objects.txt")).read().splitlines() if l]
with open(os.path.join(HERE, "objs.rsp"), "w") as f:
    for o in objs:
        f.write('"%s"\n' % o)
CC = ["psp-gcc", "-G0", "-O2"]
LINK = CC + ["-L" + SDK + "/lib", "-specs=" + SDK + "/lib/prxspecs", "-Wl,-q,-T" + SDK + "/lib/linkfile.prx",
             "-Wl,-zmax-page-size=128", "-Wl,--gc-sections"]
LIBS = ["-lm", "-lpspdebug", "-lpspdisplay", "-lpspge", "-lpspctrl", "-lpsppower", "-lpsprtc", "-lpspaudio"]

def run(cmd):
    return subprocess.run(cmd, cwd=HERE, capture_output=True, text=True)

r = run(CC + ["-I" + SDK + "/include", "-c", "psp_module.c", "-o", "psp_module.o"])
assert r.returncode == 0, r.stderr
stubs = set()
for attempt in range(4):
    with open(os.path.join(HERE, "stubs.c"), "w") as f:
        f.write("/* generated by link.py: every symbol the game uses that nothing defines yet */\n")
        for s in sorted(stubs):
            f.write("int %s(void) { return 0; }\n" % s)
    r = run(CC + ["-w", "-c", "stubs.c", "-o", "stubs.o"])
    assert r.returncode == 0, r.stderr[-2000:]
    r = run(LINK + ["psp_module.o", "stubs.o", "@objs.rsp", SDK + "/lib/prxexports.o"] + LIBS + ["-o", "halo.elf"])
    missing = set(re.findall(r"undefined reference to `([^']+)'", r.stderr))
    print("link attempt %d: %d new undefined symbols" % (attempt + 1, len(missing - stubs)))
    if r.returncode == 0:
        break
    if not (missing - stubs):
        print(r.stderr[-3000:])
        break
    stubs |= missing
open(os.path.join(HERE, "stubbed_symbols.txt"), "w").write("\n".join(sorted(stubs)) + "\n")
if r.returncode == 0:
    print(run(["psp-size", "-A", "halo.elf"]).stdout)
    print(run(["psp-size", "halo.elf"]).stdout)
print("stubbed symbols: %d (stubbed_symbols.txt)" % len(stubs))
