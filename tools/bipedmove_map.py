#!/usr/bin/env python3
"""Write psp/include/psp_bipedmove_map.h: each biped datum byte's place in the
world store's biped record, as a constant table, so the intent's accessor
(PSP_BMS, psp_bipedmove.h) folds to one load at each field when its offset is
a constant. Read from box_world_store.h and box_world_store_biped.h with the
same layout rules as box_ws_init (owner sections end to end, then biped
motion's unit2 and read2); box_world_store.c checks the table against the one
it builds at launch and leaves the store off if they differ.

  python3 tools/bipedmove_map.py          # write the header
  python3 tools/bipedmove_map.py --check  # exit 1 if the header is stale
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
GEN = ROOT / "psp/src/box_world_store.h"
ADD = ROOT / "psp/src/box_world_store_biped.h"
OUT = ROOT / "psp/include/psp_bipedmove_map.h"
DATUM_BYTES = 1152

def size(text, name):
    m = re.search(r"struct box_ws_biped_%s \{\s*/\* (\d+) B \*/" % name, text)
    if not m:
        sys.exit("bipedmove_map: no size for box_ws_biped_%s" % name)
    return int(m.group(1))

def runs(text, name):
    m = re.search(r"static const struct box_ws_run %s\[\] = \{(.*?)\};" % name, text, re.S)
    if not m:
        sys.exit("bipedmove_map: no %s" % name)
    return [tuple(map(int, r)) for r in re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", m.group(1))]

def build():
    gen, add = GEN.read_text(), ADD.read_text()
    owners = [size(gen, n) for n in ("read", "unit", "posing", "walk", "control")]
    gen_bytes = sum(owners)
    unit2 = size(add, "unit2")
    placed = []  # (datum, record, bytes)
    owner, base = 0, 0
    for i, (d, s, b) in enumerate(runs(gen, "box_ws_biped_runs")):
        if i and s == 0:
            base += owners[owner]
            owner += 1
        if s + b > owners[owner]:
            sys.exit("bipedmove_map: run %d past its section" % i)
        placed.append((d, base + s, b))
    if owner != len(owners) - 1:
        sys.exit("bipedmove_map: runs end in section %d" % owner)
    placed += [(d, gen_bytes + s, b) for d, s, b in runs(add, "box_ws_biped_unit2_runs")]
    placed += [(d, gen_bytes + unit2 + s, b) for d, s, b in runs(add, "box_ws_biped_read2_runs")]
    table = [-1] * DATUM_BYTES
    for d, r, b in placed:
        for j in range(b):
            if table[d + j] >= 0:
                sys.exit("bipedmove_map: datum +%d held twice" % (d + j))
            table[d + j] = r + j
    lines = ["/* Generated by tools/bipedmove_map.py from box_world_store.h and",
             "   box_world_store_biped.h: do not edit. Each biped datum byte's place in",
             "   the world store's biped record, -1 where the store doesn't hold it. */",
             "#pragma once",
             "static const short box_ws_move_map_c[%d] = {" % DATUM_BYTES]
    for k in range(0, DATUM_BYTES, 16):
        lines.append("\t" + ", ".join(str(v) for v in table[k:k + 16]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"

text = build()
if "--check" in sys.argv:
    sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
OUT.write_text(text)
