#!/usr/bin/env python3
"""Write psp/include/psp_bipedmove_map.h: each biped datum byte's place in the
world store's biped record, as a constant table, so the intent's accessor
(PSP_BMS, psp_bipedmove.h) folds to one load at each field when its offset is
a constant. Read from box_world_store.h and box_world_store_biped.h with the
same layout rules as box_ws_init (owner sections end to end, then biped
motion's unit2, read2 and unit.animation held whole, the generated runs
inside it left out), and which bytes the window writes back; box_world_store.c checks the table against the one
it builds at launch and leaves the store off if they differ.

  python3 tools/bipedmove_map.py          # write the header
  python3 tools/bipedmove_map.py --check  # exit 1 if the header is stale
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
GEN = ROOT / "psp/src/box_world_store.h"
ADD = ROOT / "psp/src/box_world_store_biped.h"
OUT = ROOT / "psp/include/psp_bipedmove_map.h"
DATUM_BYTES = 1152

def size(text, name):
    m = re.search(r"struct box_ws_biped_%s \{\s*/\* (\d+) B \*/" % name, text)
    if not m:
        sys.exit("bipedmove_map: no size for box_ws_biped_%s" % name)
    return int(m.group(1))

def runs(text, name):
    m = re.search(r"static const struct box_ws_run %s\[\] = \{(.*?)\};" % name, text, re.S)
    if not m:
        sys.exit("bipedmove_map: no %s" % name)
    return [tuple(map(int, r)) for r in re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", m.group(1))]

def build():
    gen, add = GEN.read_text(), ADD.read_text()
    owners = [size(gen, n) for n in ("read", "unit", "posing", "walk", "control")]
    gen_bytes = sum(owners)
    unit2 = size(add, "unit2")
    placed = []  # (datum, record, bytes)
    owner, base = 0, 0
    for i, (d, s, b) in enumerate(runs(gen, "box_ws_biped_runs")):
        if i and s == 0:
            base += owners[owner]
            owner += 1
        if s + b > owners[owner]:
            sys.exit("bipedmove_map: run %d past its section" % i)
        placed.append((d, base + s, b))
    if owner != len(owners) - 1:
        sys.exit("bipedmove_map: runs end in section %d" % owner)
    # a field held whole (unit.animation) leaves out the generated runs inside it
    whole = runs(add, "box_ws_biped_anim_runs")
    inside = lambda d, b: any(w <= d and d + b <= w + wb for w, _, wb in whole)
    for d, r, b in placed:
        if not inside(d, b) and any(d < w + wb and w < d + b for w, _, wb in whole):
            sys.exit("bipedmove_map: run at +%d crosses a field held whole" % d)
    # owners: 0 read, 1 unit, 2 posing, 3 walk, 4 control
    owner_of = []
    owner, k = 0, 0
    for i, (d, s, b) in enumerate(runs(gen, "box_ws_biped_runs")):
        if i and s == 0:
            owner += 1
        owner_of.append(owner)
    placed = [(d, r, b, o) for (d, r, b), o in zip(placed, owner_of) if not inside(d, b)]
    read2 = size(add, "read2")
    placed += [(d, gen_bytes + s, b, 1) for d, s, b in runs(add, "box_ws_biped_unit2_runs")]
    placed += [(d, gen_bytes + unit2 + s, b, 0) for d, s, b in runs(add, "box_ws_biped_read2_runs")]
    placed += [(d, gen_bytes + unit2 + read2 + s, b, 1) for d, s, b in whole]
    m = re.search(r"box_ws_biped_move_back\[\] = \{([^}]*)\}", add)
    if not m:
        sys.exit("bipedmove_map: no box_ws_biped_move_back")
    back_runs = [int(x) for x in re.findall(r"\d+", m.group(1))]
    for d in back_runs:
        if not any(p[0] == d for p in placed):
            sys.exit("bipedmove_map: box_ws_biped_move_back +%d isn't a run's start" % d)
    table = [-1] * DATUM_BYTES
    back = [0] * DATUM_BYTES
    for d, r, b, o in placed:
        for j in range(b):
            if table[d + j] >= 0:
                sys.exit("bipedmove_map: datum +%d held twice" % (d + j))
            table[d + j] = r + j
            back[d + j] = 1 if o in (1, 4) or d in back_runs else 0
    lines = ["/* Generated by tools/bipedmove_map.py from box_world_store.h and",
             "   box_world_store_biped.h: do not edit. Each biped datum byte's place in",
             "   the world store's biped record, -1 where the store doesn't hold it. */",
             "#pragma once",
             "static const short box_ws_move_map_c[%d] = {" % DATUM_BYTES]
    for k in range(0, DATUM_BYTES, 16):
        lines.append("\t" + ", ".join(str(v) for v in table[k:k + 16]) + ",")
    lines.append("};")
    sums = [0]
    for v in back:
        sums.append(sums[-1] + v)
    lines += ["/* The bytes before each datum offset whose run is written back at the",
              "   window's end (unit, control and box_ws_biped_move_back), so a field's",
              "   count is two loads: PSP_BMSW refuses a write to a held field that",
              "   isn't written back whole */",
              "static const unsigned short box_ws_move_back_sum_c[%d] = {" % (DATUM_BYTES + 1)]
    for k in range(0, DATUM_BYTES + 1, 24):
        lines.append("\t" + ", ".join(str(v) for v in sums[k:k + 24]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"

text = build()
if "--check" in sys.argv:
    sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
OUT.write_text(text)
