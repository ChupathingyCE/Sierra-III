#!/usr/bin/env python3
"""Write psp/include/psp_bmsb_map.h: biped motion's means B record
(docs/box_biped_motion.md, "Means B"), the biped datum's fields it holds and
where each sits in it, as constant tables, so each of the window's accesses
(PSP_BMS, psp_bmsb.h) folds when it's compiled to a plain load from the
record or from the datum: no compare at run time.

The fields are RUNS below, settled by means B's census (the lab's msbcensus1):
fields only the window's own functions touch from the fill after the unit
pass to the write-back after the solves. Each run is a datum offset, its
bytes, and whether the window writes it (written back after the solves) or
only reads it (filled, never written back). The record packs them in datum
order, at most 256 bytes.

  python3 tools/bmsb_map.py          # write the header
  python3 tools/bmsb_map.py --check  # exit 1 if the header is stale
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "psp/include/psp_bmsb_map.h"
DATUM_BYTES = 1152
RECORD_LIMIT = 256

# (datum offset, bytes, written by the window): the census's field list
RUNS = [
    (1066, 1, True),   # biped.state
    (1113, 2, True),   # biped.airborne_ticks, slipping_ticks
    (1124, 24, True),  # biped.crouch, bank, ground_plane
]

def build():
    runs = sorted(RUNS)
    placed, at = [], 0
    for d, b, w in runs:
        if placed and placed[-1][0] + placed[-1][2] > d:
            sys.exit("bmsb_map: runs overlap at +%d" % d)
        # a run's place keeps the datum's alignment within 4 bytes, so a
        # field's loads stay aligned (unaligned word loads fault on the PSP)
        at += (d - at) % 4
        placed.append((d, at, b, w))
        at += b
    size = (at + 3) & ~3
    if size > RECORD_LIMIT:
        sys.exit("bmsb_map: the record is %d bytes, over %d" % (size, RECORD_LIMIT))
    table = [-1] * DATUM_BYTES
    back = [0] * DATUM_BYTES
    for d, r, b, w in placed:
        for j in range(b):
            table[d + j] = r + j
            back[d + j] = 1 if w else 0
    held_sum, back_sum = [0], [0]
    for k in range(DATUM_BYTES):
        held_sum.append(held_sum[-1] + (table[k] >= 0))
        back_sum.append(back_sum[-1] + back[k])

    def merged(only_back):
        out = []
        for d, r, b, w in placed:
            if only_back and not w:
                continue
            if out and out[-1][0] + out[-1][2] == d and out[-1][1] + out[-1][2] == r:
                out[-1] = (out[-1][0], out[-1][1], out[-1][2] + b)
            else:
                out.append((d, r, b))
        return out

    def array(name, kind, values, per):
        lines = ["static const %s %s[%d] = {" % (kind, name, len(values))]
        for k in range(0, len(values), per):
            lines.append("\t" + ", ".join(str(v) for v in values[k:k + per]) + ",")
        return lines + ["};"]

    lines = ["/* Generated by tools/bmsb_map.py: do not edit. Biped motion's means B",
             "   record: each biped datum byte's place in it (-1 where it isn't held),",
             "   the bytes held and written back before each datum offset, and the",
             "   copy runs (datum offset, record offset, bytes). */",
             "#pragma once",
             "#define PSP_BMSB_BYTES %d" % size]
    lines += array("psp_bmsb_map_c", "short", table, 16)
    lines += array("psp_bmsb_held_sum_c", "unsigned short", held_sum, 24)
    lines += array("psp_bmsb_back_sum_c", "unsigned short", back_sum, 24)
    for name, only in (("psp_bmsb_fill_runs", False), ("psp_bmsb_back_runs", True)):
        rs = merged(only)
        lines.append("#define %s_COUNT %d" % (name.upper(), len(rs)))
        lines.append("static const unsigned short %s[%d][3] = {" % (name, max(len(rs), 1)))
        lines += ["\t{ %d, %d, %d }," % r for r in rs] or ["\t{ 0, 0, 0 },"]
        lines.append("};")
    return "\n".join(lines) + "\n"

text = build()
if "--check" in sys.argv:
    sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
OUT.write_text(text)
